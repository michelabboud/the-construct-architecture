  // --------------------------------------------------------------------------
  // TEMPLATE SYSTEM
  // --------------------------------------------------------------------------

  /**
   * Expand a template with variables
   */
  expandTemplate(template: string, variables: Record<string, unknown>): string {
    let result = template;

    // Process #each blocks
    result = result.replace(TEMPLATE_EACH_PATTERN, (_match, arrayName, content) => {
      const array = variables[arrayName];
      if (!Array.isArray(array)) return '';

      return array.map((item, index) => {
        let itemContent = content;
        if (typeof item === 'object' && item !== null) {
          // Replace {{this.property}} with item properties
          itemContent = itemContent.replace(/\{\{this\.(\w+)\}\}/g, (_: string, prop: string) => {
            return String((item as Record<string, unknown>)[prop] ?? '');
          });
        }
        // Replace {{this}} with the item itself
        itemContent = itemContent.replace(/\{\{this\}\}/g, String(item));
        // Replace {{@index}} with the index
        itemContent = itemContent.replace(/\{\{@index\}\}/g, String(index));
        return itemContent;
      }).join('');
    });

    // Process #if blocks
    result = result.replace(TEMPLATE_IF_PATTERN, (_match, varName, content) => {
      const value = variables[varName];
      return value ? content : '';
    });

    // Process #unless blocks
    result = result.replace(TEMPLATE_UNLESS_PATTERN, (_match, varName, content) => {
      const value = variables[varName];
      return !value ? content : '';
    });

    // Process simple variables
    result = result.replace(TEMPLATE_VAR_PATTERN, (_match, varName) => {
      const value = variables[varName];
      if (value === undefined || value === null) return '';
      return String(value);
    });

    return result;
  }

  /**
   * Register a custom template
   */
  registerTemplate(name: string, template: string): void {
    this.templateCache.set(name, template);
  }

  /**
   * Get a registered template
   */
  getTemplate(name: string): string | undefined {
    return this.templateCache.get(name);
  }

  /**
   * Clear template cache
   */
  clearTemplateCache(): void {
    this.templateCache.clear();
  }

