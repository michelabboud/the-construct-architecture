  /**
   * Extract fields from contract for type generation
   */
  private extractContractFields(
    contract: GeneratedContract,
    fieldType: 'input' | 'output'
  ): Array<{ name: string; zodType: string }> {
    const fields: Array<{ name: string; zodType: string }> = [];

    // If we have source prompt, use its variables
    if (contract.sourcePrompt && fieldType === 'input') {
      for (const variable of contract.sourcePrompt.variables) {
        fields.push({
          name: variable.name,
          zodType: this.inferZodType(variable.type || 'string'),
        });
      }
    }

    // Default fields if none found
    if (fields.length === 0) {
      if (fieldType === 'input') {
        fields.push({ name: 'input', zodType: 'z.string()' });
      } else {
        fields.push({ name: 'result', zodType: 'z.string()' });
      }
    }

    return fields;
  }

  /**
   * Infer Zod type from variable type
   */
  private inferZodType(type: string): string {
    switch (type.toLowerCase()) {
      case 'string':
        return 'z.string()';
      case 'number':
        return 'z.number()';
      case 'boolean':
        return 'z.boolean()';
      case 'array':
        return 'z.array(z.unknown())';
      case 'object':
        return 'z.record(z.unknown())';
      default:
        return 'z.string()';
    }
  }

