  /**
   * Generate a contract from a prompt analysis
   */
  async generateContract(prompt: PromptAnalysis): Promise<GeneratedContract> {
    const id = this.generateContractId(prompt);
    const name = this.generateContractName(prompt);

    // Extract from structure
    const systemPrompt = prompt.structure.systemPromptContent;
    const userTemplate = prompt.structure.userPromptTemplate;

    // Analyze the prompt to determine contract properties
    const contractType = this.inferContractType(prompt);
    const objectives = this.extractObjectives(prompt);
    const constraints = this.extractConstraints(prompt);
    const warnings: string[] = [];

    // Check for potential issues
    if (!systemPrompt && !userTemplate) {
      warnings.push('No prompts detected - contract may be incomplete');
    }

    if (prompt.variables.length === 0) {
      warnings.push('No variables detected - prompt may be static');
    }

    // Build template variables
    const templateVars: Record<string, unknown> = {
      id,
      name,
      type: contractType,
      sourcePath: prompt.location.file,
      createdAt: new Date().toISOString().split('T')[0],
      priority: 'normal',
      tags: this.generateTags(prompt),
      description: this.generateDescription(prompt),
      hasTools: false, // Tools are analyzed separately via ToolAnalysis
      tools: [],
      goalDescription: `Execute the ${name} operation successfully`,
      objectives,
      successThreshold: 8,
      forbiddenActions: ['Modify files without confirmation', 'Execute destructive operations'],
      constraints,
      hasPrompts: Boolean(systemPrompt || userTemplate),
      systemPrompt: systemPrompt || 'You are a helpful AI assistant.',
      userPrompt: this.convertToTemplatePrompt(userTemplate, prompt.variables),
      maxDuration: 30000,
      maxRetries: 3,
    };

    const content = this.expandTemplate(CONTRACT_TEMPLATE, templateVars);

    // Calculate confidence based on prompt completeness
    const confidence = this.calculateConfidence(prompt);

    return {
      id,
      name,
      sourcePrompt: prompt,
      content,
      outputPath: `contracts/${id}.yaml`,
      confidence,
      warnings,
    };
  }

  /**
   * Generate multiple contracts from prompt analyses
   */
  async generateContracts(prompts: PromptAnalysis[]): Promise<GeneratedContract[]> {
    const contracts: GeneratedContract[] = [];

    for (const prompt of prompts) {
      const contract = await this.generateContract(prompt);
      contracts.push(contract);
    }

    return contracts;
  }

  /**
   * Generate a contract ID from prompt analysis
   */
  private generateContractId(prompt: PromptAnalysis): string {
    // Use prompt ID if meaningful
    if (prompt.id && prompt.id !== 'unknown') {
      return this.toKebabCase(prompt.id);
    }

    // Try to infer from file name
    const fileName = prompt.location.file.split('/').pop() || 'unknown';
    const baseName = fileName.replace(/\.(ts|js|tsx|jsx)$/, '');
    return this.toKebabCase(baseName);
  }

  /**
   * Generate a contract name from prompt analysis
   */
  private generateContractName(prompt: PromptAnalysis): string {
    // Use prompt ID or file name
    if (prompt.id && prompt.id !== 'unknown') {
      return this.toTitleCase(prompt.id);
    }

    const fileName = prompt.location.file.split('/').pop() || 'Generated';
    const baseName = fileName.replace(/\.(ts|js|tsx|jsx)$/, '');
    return this.toTitleCase(baseName);
  }

  /**
   * Infer contract type from prompt analysis
   */
  private inferContractType(prompt: PromptAnalysis): string {
    const systemPrompt = prompt.structure.systemPromptContent;
    const userTemplate = prompt.structure.userPromptTemplate;

    if (systemPrompt?.includes('chat') || userTemplate?.includes('conversation')) {
      return 'chat';
    }
    if (systemPrompt?.includes('embed') || userTemplate?.includes('vector')) {
      return 'embedding';
    }
    return 'completion';
  }

  /**
   * Extract objectives from prompt analysis
   */
  private extractObjectives(prompt: PromptAnalysis): string[] {
    const objectives: string[] = [];

    if (prompt.structure.hasSystemPrompt) {
      objectives.push('Follow system prompt guidelines');
    }

    if (prompt.variables.length > 0) {
      objectives.push(`Process ${prompt.variables.length} input variable(s)`);
    }

    if (prompt.complexity === 'complex') {
      objectives.push('Handle complex multi-step processing');
    }

    if (objectives.length === 0) {
      objectives.push('Complete the requested task');
    }

    return objectives;
  }

  /**
   * Extract constraints from prompt analysis
   */
  private extractConstraints(prompt: PromptAnalysis): string[] {
    const constraints: string[] = [];
    const systemPrompt = prompt.structure.systemPromptContent;

    // Look for constraints in system prompt
    if (systemPrompt) {
      const constraintPatterns = [
        /must\s+not\s+([^.]+)/gi,
        /never\s+([^.]+)/gi,
        /don't\s+([^.]+)/gi,
        /avoid\s+([^.]+)/gi,
      ];

      for (const pattern of constraintPatterns) {
        let match;
        while ((match = pattern.exec(systemPrompt)) !== null) {
          constraints.push(match[1]!.trim());
        }
      }
    }

    if (constraints.length === 0) {
      constraints.push('Follow standard safety guidelines');
      constraints.push('Validate inputs before processing');
    }

    return constraints;
  }

  /**
   * Generate tags for a contract
   */
  private generateTags(prompt: PromptAnalysis): string[] {
    const tags: string[] = ['generated', 'morpheus'];

    if (prompt.type === 'template') {
      tags.push('template');
    }

    if (prompt.complexity === 'complex') {
      tags.push('complex');
    }

    return tags;
  }

  /**
   * Generate description for a contract
   */
  private generateDescription(prompt: PromptAnalysis): string {
    return `Generated contract from ${prompt.type} prompt at ${prompt.location.file}`;
  }

  /**
   * Convert user template to Construct template format
   */
  private convertToTemplatePrompt(template: string | undefined, variables: PromptVariable[]): string {
    if (!template) {
      if (variables.length > 0) {
        return variables.map(v => `{{${v.name}}}`).join('\n');
      }
      return '{{input}}';
    }

    // Convert various template formats to Mustache-style
    let converted = template;

    // Python f-string style: {variable}
    converted = converted.replace(/\{(\w+)\}/g, '{{$1}}');

    // JavaScript template literal style: ${variable}
    converted = converted.replace(/\$\{(\w+)\}/g, '{{$1}}');

    return converted;
  }

  /**
   * Calculate confidence score for generated contract
   */
  private calculateConfidence(prompt: PromptAnalysis): number {
    let confidence = 0.5; // Base confidence

    if (prompt.structure.hasSystemPrompt) confidence += 0.15;
    if (prompt.structure.hasUserPrompt) confidence += 0.15;
    if (prompt.variables.length > 0) confidence += 0.1;
    if (prompt.type === 'template') confidence += 0.05;
    if (prompt.complexity !== 'complex') confidence += 0.05;

    return Math.min(confidence, 1.0);
  }

